fail = 0
for lemma, group, gold in GOLD:
    want = gold.split()
    for (p, n), w in zip(SLOTS, want):
        got = conjugate(lemma, group, p, n)
        if got != w:
            fail += 1
            print(u'%s %d%s: got %s want %s' % (lemma, p, n, got, w))
for g, c, n, w in DIKOS:
    got = dikos(g, c, n)
    if got != w:
        fail += 1
        print(u'δικός %s %s %s: got %s want %s' % (g, c, n, got, w))
for key, nxt, w in NU:
    from pron import weak_acc as wa
    got = wa(key, nxt)
    if got != w:
        fail += 1
        print(u'weak_acc %s before %s: got %s want %s' % (key, nxt, got, w))

print(u'%d failures out of %d paradigms' % (fail, len(GOLD)))
sys.exit(1 if fail else 0)
